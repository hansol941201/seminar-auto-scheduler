'use strict';
const http=require('node:http');
const {initializeApp,applicationDefault}=require('firebase-admin/app');
const {getAuth}=require('firebase-admin/auth');
const {getFirestore}=require('firebase-admin/firestore');
const {createStore}=require('./firestore-store.cjs');
const {createHandler}=require('./api.cjs');
const {createKakao}=require('./routing.cjs');
const {failure}=require('./policy.cjs');
const SourceReader=require('../source-reader.js');
const project=process.env.SEMINAR_FIREBASE_PROJECT_ID;
if(!project||project==='test-168a4')throw Error('원본과 분리된 세미나 전용 Firebase 프로젝트가 필요합니다.');
const clientConfig=JSON.parse(process.env.FIREBASE_WEB_CONFIG||'{}');
if(clientConfig.projectId!==project||!clientConfig.apiKey||!clientConfig.authDomain)throw Error('세미나 전용 Firebase 웹 인증 설정이 필요합니다.');
const allowedOrigin=process.env.ALLOWED_ORIGIN;if(!allowedOrigin||new URL(allowedOrigin).origin!==allowedOrigin)throw Error('허용할 웹사이트 origin을 지정하세요.');
const app=initializeApp({credential:applicationDefault(),projectId:project});
const db=getFirestore(app),store=createStore(db,process.env.SEMINAR_WORKSPACE_ID||'seminar');
const limit=Number(process.env.MAPS_DAILY_CALL_LIMIT||300);if(!Number.isInteger(limit)||limit<1||limit>10000)throw Error('지도 API 호출 상한을 확인하세요.');
const provider=createKakao({key:process.env.KAKAO_REST_API_KEY,consume:()=>store.consumeRoute(limit)});
const authenticate=async header=>{if(!header.startsWith('Bearer '))throw failure('로그인이 필요합니다.',401);try{const token=await getAuth(app).verifyIdToken(header.slice(7),true);if(token.email_verified!==true||token.firebase?.sign_in_provider!=='google.com')throw Error();return token.uid;}catch{throw failure('회사 로그인 확인 실패',401);}};
let previousRaw=null;
const sourceLoader=async options=>{const result=await SourceReader.snapshot({...options,previousRaw});previousRaw=result.raw;return result;};
const server=http.createServer(createHandler({store,authenticate,sourceLoader,provider,clientConfig,allowedOrigin}));
server.requestTimeout=30000;server.headersTimeout=15000;server.listen(Number(process.env.PORT||8080),'0.0.0.0');
